import { selectOption, apiResponse, TS } from './common.mjs'
export default async ({ page, api, shot, log, admin, base, b }) => {
  await page.goto(`${admin}/wholesale-prices`)
  await page.waitForLoadState('networkidle')
  await page.getByPlaceholder('Search product name, ID, slug, or SKU').fill(`qa-product-${TS}`)
  await page.getByPlaceholder('Search product name, ID, slug, or SKU').press('Enter')
  await page.waitForTimeout(1500)
  const row = page.locator('tbody tr', { hasText: `qa-product` }).first()
  await row.getByRole('button', { name: 'Configure' }).click()
  const dlg = page.locator('[role=dialog]').last()
  await dlg.getByRole('button', { name: 'Add tier' }).click()
  await dlg.getByRole('button', { name: 'Add tier' }).click()
  await dlg.getByRole('button', { name: 'Add tier' }).click()
  const nums = dlg.locator('input')
  log('inputs', await nums.count())
  // tier 1: all SKUs qty 5 price 9.00 ; tier 2: STD qty 10 price 8.00 ; tier3 invalid: qty 0
  const selects = dlg.locator('select')
  log('sku opts', (await selects.first().locator('option').allTextContents()).join(' / '))
  const tiers = dlg.locator('div.grid', { has: page.locator('input') })
  const inp = dlg.locator('input[type=number], input[inputmode]')
  log('numeric inputs', await inp.count())
  await inp.nth(0).fill('5'); await inp.nth(1).fill('9.00')
  await selectOption(selects.nth(1), /Standard/)
  await inp.nth(2).fill('10'); await inp.nth(3).fill('8.00')
  await inp.nth(4).fill('0'); await inp.nth(5).fill('30')
  await shot(page, 'c-wholesale-modal')
  await dlg.getByRole('button', { name: 'Save' }).click()
  await page.waitForTimeout(1500)
  log('invalid tier save msg:', (await page.locator('[role=status]').allInnerTexts()).join(' | '), '| dialog errs:', (await dlg.locator('.text-danger-text').allInnerTexts().catch(() => [])).join('/'))
  // remove tier 3
  await dlg.getByRole('button', { name: 'Remove' }).nth(2).click()
  const r = await apiResponse(page, 'PATCH', /wholesale-prices$/, () => dlg.getByRole('button', { name: 'Save' }).click())
  log('saved', JSON.stringify(r.wholesale_prices ?? r).slice(0, 500))
  await page.waitForTimeout(800)
  await shot(page, 'c-wholesale-list')
  const pub = await page.evaluate(async (s) => (await (await fetch(`/api/v1/public/products/${s}`)).json()), `qa-product-${TS}`)
  log('public wholesale', JSON.stringify(pub.data.wholesale_prices ?? pub.data.skus?.map((k) => k.wholesale_prices)).slice(0, 500))
  // storefront page
  const sp = await page.context().newPage()
  await sp.goto(`${base}/products/qa-product-${TS}`)
  await sp.waitForLoadState('networkidle')
  await sp.waitForTimeout(1500)
  await sp.screenshot({ path: 'live/shots/admin/c-sf-product-wholesale.png', fullPage: true })
  log('storefront text wholesale', (await sp.locator('body').innerText()).match(/(批发|Wholesale|wholesale)[\s\S]{0,200}/)?.[0]?.replace(/\s+/g, ' '))
}
